// Writes core/v1/logos.js from the image files in this folder.
//
// The Code Editor's ui.Label only shows data URIs: an imageUrl pointing at
// another site renders an empty 0x0 label with no error. So the logos go into a
// module as base64, and this folder stays the source.
//
//     node logos/build.js
//
// Run it after adding or replacing a logo, and commit both.

var fs = require('fs');
var path = require('path');

var LOGOS = {
    toolkit: 'mapbiomas-toolkit-logo.png',
    agua: 'mapbiomas-agua-logo.png',
    fire: 'mapbiomas-fire-logo.png',
    solo: 'mapbiomas-solo-logo.png',
    degradacao: 'mapbiomas-degradacao-logo.jpg'
};

var TYPES = { '.png': 'image/png', '.jpg': 'image/jpeg' };

var lines = [
    '/**',
    ' * @name',
    ' *      core/v1/logos.js',
    ' *',
    ' * @description',
    ' *      The panel logos as data URIs. Generated by `node logos/build.js` from the',
    ' *      files in logos/; don\'t edit by hand.',
    ' *',
    ' *      ui.Label shows only data URIs: an imageUrl on another site renders an',
    ' *      empty label. The logos used to be .b64 files in gs://mapbiomas-public,',
    ' *      which started returning 403.',
    ' *',
    ' * @see',
    ' *      https://github.com/mapbiomas/user-toolkit/tree/master/logos',
    ' */',
    ''
];

Object.keys(LOGOS).forEach(function (key) {
    var file = path.join(__dirname, LOGOS[key]);
    var type = TYPES[path.extname(file)];
    var b64 = fs.readFileSync(file).toString('base64');
    lines.push('exports.' + key + " = 'data:" + type + ';base64,' + b64 + "';");
    lines.push('');
});

var out = path.join(__dirname, '..', 'core', 'v1', 'logos.js');
fs.writeFileSync(out, lines.join('\n'));
console.log('wrote ' + path.relative(process.cwd(), out));
